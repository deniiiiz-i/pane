const triggerAsChild = { asChild: true } as const;

function SidebarMenuButton({
  asChild = false,
  isActive = false,
  variant = "default",
  size = "default",
  tooltip,
  className,
  children,
  ...props
}: React.ComponentProps<"button"> & {
  asChild?: boolean;
  isActive?: boolean;
  tooltip?: string | React.ComponentProps<typeof TooltipContent>;
} & VariantProps<typeof sidebarMenuButtonVariants>) {
  const Comp = asChild ? Slot.Root : "button";
  const { isMobile, state, indicatorId } = useSidebar();

  const button = (
    <Comp
      data-slot="sidebar-menu-button"
      data-sidebar="menu-button"
      data-size={size}
      data-active={isActive}
      className={cn(sidebarMenuButtonVariants({ variant, size }), className)}
      {...props}
    >
      {isActive ? (
        <Pane
          layoutId={indicatorId}
          transition={GLASS_SPRING.hover}
          variant="clear"
          radius={12}
          className="-z-10 absolute inset-0"
        />
      ) : null}
      {/* with asChild the pill is slotted into the child (a link, say)
          rather than replacing it */}
      {asChild ? <Slot.Slottable>{children}</Slot.Slottable> : children}
    </Comp>
  );

  if (!tooltip) {
    return button;
  }

  if (typeof tooltip === "string") {
    tooltip = {
      children: tooltip,
    };
  }

  return (
    <Tooltip>
      {/* asChild goes through a spread on purpose: shadcn's install
          transform for base-* styles drops a literal `asChild` attribute
          here, which would nest the menu button inside the trigger's own */}
      <TooltipTrigger {...triggerAsChild}>{button}</TooltipTrigger>
      <TooltipContent
        side="right"
        align="center"
        hidden={state !== "collapsed" || isMobile}
        {...tooltip}
      />
    </Tooltip>
  );
}

